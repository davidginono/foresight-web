import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
import { heroAssets } from '../src/heroImages.js';

const dimensions = JSON.parse(await fs.readFile('src/imageDimensions.json', 'utf8'));
const heroes = new Map(heroAssets.map(hero => [hero.src, hero.source || hero.src]));
const variants = {};
await fs.mkdir('public/assets/images', { recursive: true });
for (const source of [...new Set([...Object.keys(dimensions), ...heroes.keys()])].sort()) {
  if (!/\.(png|jpe?g|webp)$/i.test(source)) continue;
  const input = await fs.readFile('public' + (heroes.get(source) || source));
  if (!heroes.has(source) && input.length < 96 * 1024) continue;
  const metadata = await sharp(input).metadata();
  const widths = [...new Set((heroes.has(source) ? [960, 1920] : [480, 960, 1600]).map(width => Math.min(width, metadata.width)))];
  const hash = createHash('sha256').update(input).update('webp-q78-v1').digest('hex').slice(0, 16);
  const candidates = [];
  for (const width of widths) {
    const url = `/assets/images/${hash}-${width}.webp`;
    await sharp(input).resize({ width, withoutEnlargement: true }).webp({ quality: 78, effort: 5 }).toFile('public' + url);
    candidates.push({ src: url, width });
  }
  variants[source] = {
    src: candidates.at(-1).src,
    srcSet: candidates.map(candidate => `${candidate.src} ${candidate.width}w`).join(', '),
    width: metadata.width, height: metadata.height,
  };
  if (heroes.has(source)) {
    variants[source].mobile = candidates[0].src;
    const preview = await sharp(input).resize({ width: 48 }).webp({ quality: 35 }).toBuffer();
    variants[source].preview = `data:image/webp;base64,${preview.toString('base64')}`;
  }
}
await fs.writeFile('src/imageVariants.js', `// Generated by npm run optimize:images. Original assets remain unchanged.\nexport default ${JSON.stringify(variants, null, 2)};\n`);
console.log(`Prepared responsive copies for ${Object.keys(variants).length} images, including ${heroes.size} heroes.`);
